# from langchain_core.utils.pydantic import BaseModel, Field
from pydantic import BaseModel, Field
from langchain_openai import ChatOpenAI
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.output_parsers import StrOutputParser

from langgraph.graph import END, StateGraph, START

from typing import List, Literal
from typing_extensions import TypedDict


class ragas_Adaptive_RAG:
    def __init__(self, retriever):
        self.retriever = retriever

    def build_graph(self):
        # LLM with function call
        llm = ChatOpenAI(
            api_key="ai",
            model="openai/gpt-oss-20b",
            base_url="http://192.168.0.110:8000/v1",
            temperature=0,
        )

        ### Retrieval Grader
        # Data model
        class GradeDocuments(BaseModel):
            """Binary score for relevance check on retrieved documents."""

            binary_score: Literal["yes", "no"] = Field(
                ..., description="Documents are relevant to the expected_documents, 'yes' or 'no'"
            )
            score_reason: str = Field(
                ..., description="binary_score에서 'yes' or 'no'라고 평가한 구체적인 이유와 근거를 한문장으로 간략히 서술"
            )

        structured_llm_grader = llm.with_structured_output(GradeDocuments)

        # Prompt
        system = """You are an objective evaluator assessing the relevance of a retrieved document to the expected_document
            Your task is to filter out completely off-topic or entirely irrelevant documents.

            CRITICAL INSTRUCTIONS:
            1. 'yes' means that the document is semantically similar to the expected_document.
            2. 'no' means the document is completely semantically unrelated to the expected_document.
            3. DO NOT require exact keyword matches. Be lenient; if there is any topical connection or underlying semantic overlap, grade it as 'yes'.

            CRITICAL: Your output MUST strictly match the following JSON format. Do not add markdown blocks or other text.
            """
        grade_prompt = ChatPromptTemplate.from_messages(
            [
                ("system", system),
                ("human", "Retrieved document: \n\n {document} \n\n Expected document: {expected_document}"),
            ]
        )

        retrieval_grader = grade_prompt | structured_llm_grader

        ### Generate
        pull = """
            Use the following pieces of retrieved context to answer the question.
            Answer based on the context as much as possible. 
            If the context is insufficient, try to give a plausible answer, but do not fabricate facts.
            Write a response that is **concise, clear, and informative**, with a length appropriate for fully answering the question:
            - Not too short, not too long
            - Typically around 50–200 words
            - Straight to the point, avoiding unnecessary details
            - Easy to read and understand
        """
        prompt = ChatPromptTemplate.from_messages(
            [
                ("system", pull),
                ("human", "Question: {question}, Context: {context} "),
            ]
        )

        # Chain
        rag_chain = prompt | llm | StrOutputParser()


        ### Hallucination Grader
        # Data model
        class GradeHallucinations(BaseModel):
            """Binary score for hallucination present in generation answer."""

            binary_score: str = Field(
                description="Answer is grounded in the facts, 'yes' or 'no'"
            )
            score_reason: str = Field(
                ..., description="binary_score를 평가한 구체적인 이유와 근거를 한문장으로 간략히 서술"
            )

        structured_llm_grader = llm.with_structured_output(GradeHallucinations)

        # Prompt
        system = """
            Your task is to determine if the answer suffers from severe hallucinations that distort the main facts.

            CRITICAL INSTRUCTIONS:
            1. 'Yes' means that the answer generated by the LLM is semantically similar to and relevant to the expected answer, and is consistent with the context.
            2. 'No' means that the answer generated by the LLM contradicts the expected answer contextually, or that the main content is completely fabricated and has no relation to the expected answer.
            3. Focus ONLY on general groundedness. Do not evaluate whether the answer completely resolves the user's question, only whether its main ideas are faithful to the context.

            Give a binary score 'yes' or 'no'.
        """
        hallucination_prompt = ChatPromptTemplate.from_messages(
            [
                ("system", system),
                ("human", "expected_answer: \n\n {expected_answer} \n\n LLM generation: {generation}"),
            ]
        )

        hallucination_grader = hallucination_prompt | structured_llm_grader


        ### Answer Grader
        # Data model
        class GradeAnswer(BaseModel):
            """Binary score to assess answer addresses question."""

            binary_score: str = Field(
                description="Answer addresses the question, 'yes' or 'no'"
            )
            score_reason: str = Field(
                ..., description="binary_score를 평가한 구체적인 이유와 근거를 한문장으로 간략히 서술"
            )

        structured_llm_grader = llm.with_structured_output(GradeAnswer)

        # Prompt
        system = """You are an objective evaluator assessing whether a generated answer successfully addresses and resolves the user's question.
            Your task is to evaluate the relevance and helpfulness of the answer.

            CRITICAL INSTRUCTIONS:
            1. 'yes' means the answer directly addresses the core intent of the question. 
            - Note: If the system correctly states that it cannot answer based on the provided context (e.g., "I don't know"), grade it as 'yes' because it properly resolved the task without hallucinating.
            2. 'no' means the answer is off-topic, evasive, ignores the main question, or provides irrelevant filler.
            3. Focus ONLY on relevance to the question. Do not evaluate factual accuracy or groundedness here.

            Give a binary score 'yes' or 'no'."""
        answer_prompt = ChatPromptTemplate.from_messages(
            [
                ("system", system),
                ("human", "User question: \n\n {question} \n\n LLM generation: {generation}"),
            ]
        )

        answer_grader = answer_prompt | structured_llm_grader

        ### Question Re-writer
        # Prompt
        system = """You are an expert question re-writer that converts an input question to a better version optimized for vectorstore retrieval. 
            Look at the input and reason about the underlying semantic intent and key entities.

            CRITICAL INSTRUCTIONS:
            1. Add relevant keywords, synonyms, or broader context that would improve search results.
            2. Remove conversational filler words.
            3. OUTPUT ONLY THE REWRITTEN QUERY. Do not include any introductory text, explanations, or quotes. Just the raw optimized string."""
        re_write_prompt = ChatPromptTemplate.from_messages(
            [
                ("system", system),
                (
                    "human",
                    "Here is the initial question: \n\n {question} \n Formulate an improved question.",
                ),
            ]
        )

        question_rewriter = re_write_prompt | llm | StrOutputParser()

        class GraphState(TypedDict):
            """
            Represents the state of our graph.

            Attributes:
                question: question
                expected_answer: expected answer about question
                expected_answer: list of expected documents which retrieved by question
                generation: LLM generation
                documents: list of documents
                rag_name: name of retriever
                hallucination_count: the maximum number counted by the hallucinatory response
            """
            question: str
            expected_answer: str
            expected_documents: List[str]
            generation: str
            documents: List[str]
            rag_name: str
            hallucination_count: int


        def retrieve(state):
            """
            Retrieve documents

            Args:
                state (dict): The current graph state

            Returns:
                state (dict): New key added to state, documents, that contains retrieved documents
            """
            print(f"---[{state.get("rag_name","Unknown_RAG")}] RETRIEVE---")
            question = state["question"]

            # Retrieval
            documents = self.retriever.invoke(question)
            return {"documents": documents, "question": question, "hallucination_count": 0}


        def generate(state):
            """
            Generate answer

            Args:
                state (dict): The current graph state

            Returns:
                state (dict): New key added to state, generation, that contains LLM generation
            """
            print(f"---[{state.get("rag_name","Unknown_RAG")}] GENERATE---")
            question = state["question"]
            documents = state["documents"]

            # RAG generation
            generation = rag_chain.invoke({"context": documents, "question": question})
            return {"documents": documents, "question": question, "generation": generation}


        def grade_documents(state):
            """
            Determines whether the retrieved documents are relevant to the question.

            Args:
                state (dict): The current graph state

            Returns:
                state (dict): Updates documents key with only filtered relevant documents
            """

            print(f"---[{state.get("rag_name","Unknown_RAG")}] CHECK DOCUMENT RELEVANCE TO QUESTION---")
            question = state["question"]
            documents = state["documents"]
            expected_docs = state["expected_documents"]

            # Score each doc
            filtered_docs = []
            for d in documents:
                score = retrieval_grader.invoke(
                    {"expected_document": expected_docs, "document": d.page_content}
                )
                if score is None:
                    print("⚠️ 파싱 실패: 기본값 'no' 적용")
                    grade = "no"
                elif isinstance(score, dict):
                    # 딕셔너리 형태로 반환되었을 경우
                    print("dict")
                    grade = score.get("binary_score", "no")
                else:
                    # Pydantic 객체 형태로 반환되었을 경우
                    grade = getattr(score, "binary_score", "no")

                if grade == "yes":
                    print(f"---[{state.get("rag_name","Unknown_RAG")}] GRADE: DOCUMENT RELEVANT---")
                    # print(f"relevant docs: {d.page_content}")
                    filtered_docs.append(d)
                else:
                    print(f"---[{state.get("rag_name","Unknown_RAG")}] GRADE: DOCUMENT NOT RELEVANT---")
                    # print(f"not relevant docs: {d.page_content}")
                    continue
            return {"documents": filtered_docs, "question": question}


        def transform_query(state):
            """
            Transform the query to produce a better question.

            Args:
                state (dict): The current graph state

            Returns:
                state (dict): Updates question key with a re-phrased question
            """

            print(f"---[{state.get("rag_name","Unknown_RAG")}] TRANSFORM QUERY---")
            question = state["question"]
            documents = state["documents"]

            # Re-write question
            better_question = question_rewriter.invoke({"question": question})
            print(f"changed query: {better_question}")
            return {"documents": documents, "question": better_question}


        def decide_to_generate(state):
            """
            Determines whether to generate an answer, or re-generate a question.

            Args:
                state (dict): The current graph state

            Returns:
                str: Binary decision for next node to call
            """

            print(f"---[{state.get("rag_name","Unknown_RAG")}] ASSESS GRADED DOCUMENTS---")
            state["question"]
            filtered_documents = state["documents"]

            if not filtered_documents:
                # All documents have been filtered check_relevance
                # We will re-generate a new query
                print(
                    "---DECISION: ALL DOCUMENTS ARE NOT RELEVANT TO QUESTION, TRANSFORM QUERY---"
                )
                return "transform_query"
            else:
                # We have relevant documents, so generate answer
                print(f"---[{state.get("rag_name","Unknown_RAG")}] DECISION: GENERATE---")
                return "generate"


        def grade_generation_v_documents_and_question(state):
            """
            Determines whether the generation is grounded in the document and answers question.

            Args:
                state (dict): The current graph state

            Returns:
                str: Decision for next node to call
            """
            count = state["hallucination_count"]
            if count > 2:
                print(f"---[{state.get("rag_name","Unknown_RAG")}] HALLUCINATION COUNTING OVER---")
                return "fail"

            print(f"---[{state.get("rag_name","Unknown_RAG")}] CHECK HALLUCINATIONS---")
            question = state["question"]
            documents = state["documents"]
            generation = state["generation"]
            expected_answer = state["expected_answer"]

            score = hallucination_grader.invoke(
                {"expected_answer": expected_answer, "generation": generation}
            )
            grade = score.binary_score

            # Check hallucination
            if grade == "yes":
                print(f"---[{state.get("rag_name","Unknown_RAG")}] DECISION: GENERATION IS GROUNDED IN DOCUMENTS---")
                # Check question-answering
                print(f"---[{state.get("rag_name","Unknown_RAG")}] GRADE GENERATION vs QUESTION---")
                score = answer_grader.invoke({"question": question, "generation": generation})
                grade = score.binary_score
                if grade == "yes":
                    print(f"---[{state.get("rag_name","Unknown_RAG")}] DECISION: GENERATION ADDRESSES QUESTION---")
                    return "useful"
                else:
                    print(f"---[{state.get("rag_name","Unknown_RAG")}] DECISION: GENERATION DOES NOT ADDRESS QUESTION---")
                    print(score.score_reason)
                    return "not useful"
            else:
                print(f"---[{state.get("rag_name","Unknown_RAG")}] DECISION: GENERATION IS NOT GROUNDED IN DOCUMENTS, RE-TRY---")
                print(score.score_reason)
                return "not supported"
            
        def check_hallucination_count(state):
            """
            Counts when hallucinations occur

            Arguments:
                state (dictionary): Current graph state

            Return:
                int: Total number of hallucinations
            """
            current_h_count = state["hallucination_count"]
            print(f"---[{state.get("rag_name","Unknown_RAG")}] HALLUCINATION COUNT: {current_h_count+1} ---")
            return {"hallucination_count": current_h_count + 1}
        
        workflow = StateGraph(GraphState)

        # Define the nodes
        workflow.add_node("retrieve", retrieve)  # retrieve
        workflow.add_node("grade_documents", grade_documents)  # grade documents
        workflow.add_node("generate", generate)  # generate
        workflow.add_node("transform_query", transform_query)  # transform_query
        workflow.add_node("check", check_hallucination_count)

        # Build graph
        workflow.add_edge(
            START, "retrieve"
        )

        workflow.add_edge("retrieve", "grade_documents")
        workflow.add_conditional_edges(
            "grade_documents",
            decide_to_generate,
            {
                "transform_query": "transform_query",
                "generate": "generate",
            },
        )
        workflow.add_edge("transform_query", "retrieve")
        workflow.add_conditional_edges(
            "generate",
            grade_generation_v_documents_and_question,
            {
                "fail": END,
                "not supported": "check",
                "useful": END,
                "not useful": "transform_query",
            },
        )
        workflow.add_edge("check", "generate")

        # Compile
        adaptive_graph = workflow.compile()

        return adaptive_graph